/** The active theme's palette. */
val LocalPalette = compositionLocalOf { DefaultPalette }

/** True when the user asked for reduced motion: no scaling or crossfades, the ring alone shows focus. */
val LocalReducedMotion = compositionLocalOf { false }

val LocalHearthType = staticCompositionLocalOf { DefaultHearthType }

@Composable
fun HearthTheme(
    palette: HearthPalette,
    reducedMotion: Boolean,
    content: @Composable () -> Unit,
) {
    val density = LocalDensity.current
    val type = remember(density, palette.ink) {
        // Only the lettering casts a shadow. Its small radius leaves the landscape untouched
        // between words, including over moving clouds and the bright daytime horizons.
        val shadow = with(density) {
            Shadow(
                color = if (palette.ink.luminance() > 0.5f) Color.Black.copy(alpha = 0.95f)
                    else Color.White.copy(alpha = 0.9f),
                offset = Offset(0f, 1.dp.toPx()),
                blurRadius = 1.5.dp.toPx(),
            )
        }
        DefaultHearthType.copy(
            clock = DefaultHearthType.clock.copy(shadow = shadow),
            date = DefaultHearthType.date.copy(shadow = shadow),
            title = DefaultHearthType.title.copy(shadow = shadow),
            focusedName = DefaultHearthType.focusedName.copy(shadow = shadow),
            temperature = DefaultHearthType.temperature.copy(shadow = shadow),
            hint = DefaultHearthType.hint.copy(shadow = shadow),
            body = DefaultHearthType.body.copy(shadow = shadow),
            action = DefaultHearthType.action.copy(shadow = shadow),
            section = DefaultHearthType.section.copy(shadow = shadow),
            dialogOption = DefaultHearthType.dialogOption.copy(shadow = shadow),
        )
    }
    val readablePalette = remember(palette) {
        // Older packs lowered secondary opacity for a shaded backdrop. On unobscured art,
        // hierarchy comes from size and weight while the lettering keeps its hue and clarity.
        palette.copy(inkMuted = palette.inkMuted.copy(alpha = palette.inkMuted.alpha.coerceAtLeast(0.94f)))
    }
    CompositionLocalProvider(
        LocalPalette provides readablePalette,
        LocalReducedMotion provides reducedMotion,
        LocalHearthType provides type,
        content = content,
    )
}

/** Shorthand for reading the theme inside composables. */
object Hearth {
    val palette: HearthPalette @Composable get() = LocalPalette.current
    val type: HearthType @Composable get() = LocalHearthType.current
    val reducedMotion: Boolean @Composable get() = LocalReducedMotion.current
}
