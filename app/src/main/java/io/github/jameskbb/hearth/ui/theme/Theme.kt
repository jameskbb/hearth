/*
 * API 26+ keeps the original variable fonts. Older devices use bundled static instances
 * with the same weights and optical sizes, generated by scripts/static-fonts.py.
 * No font download or platform variable-font support is needed on API 21 through 25.
 */
@OptIn(ExperimentalTextApi::class)
private fun literata(weight: Int, opticalSize: Float, @FontRes legacyResource: Int) =
    if (Build.VERSION.SDK_INT >= 26) {
        Font(
            R.font.literata,
            weight = FontWeight(weight),
            variationSettings = FontVariation.Settings(
                FontVariation.weight(weight),
                FontVariation.Setting("opsz", opticalSize),
            ),
        )
    } else {
        Font(legacyResource, weight = FontWeight(weight))
    }

@OptIn(ExperimentalTextApi::class)
private fun instrumentSans(weight: Int, @FontRes legacyResource: Int) =
    if (Build.VERSION.SDK_INT >= 26) {
        Font(
            R.font.instrument_sans,
            weight = FontWeight(weight),
            variationSettings = FontVariation.Settings(FontVariation.weight(weight)),
        )
    } else {
        Font(legacyResource, weight = FontWeight(weight))
    }

object HearthFonts {
    /** Literata light, cut for the 44 sp clock. */
    val LiterataClock = FontFamily(literata(300, 44f, R.font.literata_clock_light))

    /** Literata regular, cut for 30 sp titles and the focused app name. */
    val LiterataTitle = FontFamily(
        literata(400, 30f, R.font.literata_title_regular),
        literata(300, 30f, R.font.literata_title_light),
    )

    val InstrumentSans = FontFamily(
        instrumentSans(400, R.font.instrument_sans_regular),
        instrumentSans(500, R.font.instrument_sans_medium),
        instrumentSans(600, R.font.instrument_sans_semibold),
    )
}

